// Writes setup.md from the helper's one source (connectText.ts):
//   node packages/helper/scripts/write-setup-md.ts [--landing <public dir>]
// Always refreshes apps/server/src/logicpacks/connectSetup.generated.ts (served at <host>/setup.md).
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { renderSetupGuide, setupPrompt } from "../src/connectText.ts";

const here = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const repo = NodePath.join(here, "../../..");
const markdown = renderSetupGuide();
const generated = NodePath.join(repo, "apps/server/src/logicpacks/connectSetup.generated.ts");
NodeFS.writeFileSync(
  generated,
  [
    "// Generated by packages/helper/scripts/write-setup-md.ts from packages/helper/src/connectText.ts. Do not edit.",
    `export const SETUP_GUIDE_MARKDOWN = ${JSON.stringify(markdown)};`,
    `export const SETUP_PROMPT = ${JSON.stringify(setupPrompt("new"))};`,
    `export const SETUP_PROMPT_INSTALLED = ${JSON.stringify(setupPrompt("installed"))};`,
    "",
  ].join("\n"),
);
process.stdout.write(`wrote ${generated}\n`);
const landing = process.argv.indexOf("--landing");
if (landing >= 0 && process.argv[landing + 1]) {
  const file = NodePath.join(process.argv[landing + 1]!, "setup.md");
  NodeFS.writeFileSync(file, markdown);
  process.stdout.write(`wrote ${file}\n`);
}
